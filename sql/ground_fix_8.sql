-- Наземка 2.0: решения Артёма по вопросам аудита (30.10.2026). Описания — как работает в бою (shared/rt-ground.js).
--
-- BUG-026  «Порабощение» и «Внушение» технику не берут (дроидов-бойцов — берут).
-- BUG-031  отбитый джедаем болт с шансом 50 % уходит обратно в стрелка (бластер; снаряд техники, ракета и охотники бара — нет:
--          так охота на джедая осталась около половины побед, tools/events/sim.js).
-- BUG-027  пехота бьёт башни и ворота (урон ×0,3), BUG-024 Колесо и мина — без изменений: только движок.

update public.hero_abilities set description = case id
    when 'mind_enslave' then 'Чужой боец на 5 минут становится твоим. Воли ему не оставляют. Одарённых и технику не берёт.'
    when 'mind_suasion' then 'Чужой боец на 5 минут переходит под твоё начало. Одарённых и технику не берёт.'
    when 'deflect_light' then 'Клинок ловит болты. С шансом 30 процентов попавший выстрел отбит и не ранит — если герой в этот миг не рубит. Каждый второй отбитый болт бластера уходит обратно в стрелка; охотники на одарённых к этому готовы.'
  end
where id in ('mind_enslave', 'mind_suasion', 'deflect_light');

-- BUG-022  залп артиллерии — круг splash_size × 1,5 клетки боя (shared/rt-units.js, ART_SPLASH_K): 3 → 4,5
update public.unit_types set description = replace(description, 'по кругу в 3 клетки', 'по кругу в 4,5 клетки')
where id in ('rep_artillery', 'cis_artillery');
