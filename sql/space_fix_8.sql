-- Космос: размеры корабля в базе по корпусу боя (аудит space-audit, SPACE-BUG-051).
-- cis_diamond: короб базы 4×2 клетки при корпусе в бою 6×3 (1200×600 м) — соседи по базе в бою стояли друг в друге.
-- Кораблей этого класса в базе нет (размещение уже стоящих не меняется), площадка сброса (10) и полоса (14) вмещают 6×3.
-- venator оставлен 3×6: корпус шире короба на 15 м с борта — это гасит мягкое расталкивание в бою (~20 м за такт),
-- а увеличение до 4×6 изменило бы место 22 стоящих кораблей.
update public.ship_types set width_cells = 6, height_cells = 3 where id = 'cis_diamond' and (width_cells, height_cells) = (4, 2);
